/** 선택 화면에 이 순서로 깔린다 (기획서 3종 먼저, 기존 검사는 뒤에). */
export const TYPE_TESTS: TypeTestDef[] = [MENTAL, TROUBLE, GUARDIAN, CHAOS];

export function findTest(path: string | undefined): TypeTestDef | undefined {
  return TYPE_TESTS.find((t) => t.path === path);
}

/** 고른 축 목록을 축별 점수로 집계한다. */
export function scoresOf(test: TypeTestDef, answers: string[]): Record<string, number> {
  const scores = Object.fromEntries(test.axes.map((a) => [a, 0]));
  answers.forEach((axis) => {
    if (axis in scores) scores[axis] += 1;
  });
  return scores;
}

/** 축 점수 → 결과 키. resolve가 없으면 최고점 축이 곧 결과다. */
export function resultKeyOf(test: TypeTestDef, scores: Record<string, number>): string {
  if (test.resolve) return test.resolve(scores);
  return test.axes.reduce(
    (best, a) => ((scores[a] ?? 0) > (scores[best] ?? 0) ? a : best),
    test.axes[0],
  );
}
