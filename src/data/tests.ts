/**
 * 유형검사 정의 모음.
 *
 * 검사마다 축 개수(2~4)와 결과 카드 구성이 달라, 검사 하나를 통째로 기술하는
 * `TypeTestDef`를 두고 화면은 이 정의만 보고 그린다. 검사를 늘릴 때 UI는
 * 건드리지 않고 이 파일에 항목 하나만 더하면 된다.
 */

export interface TestOption {
  text: string;
  /** 이 선택지가 +1 하는 축 */
  axis: string;
}

export interface TestQuestion {
  q: string;
  o: TestOption[];
}

export interface TestResult {
  /** 카드 상단 태그 (예: '쿠쿠다스 100%') */
  tag: string;
  name: string;
  desc: string;
  /** 대처법 한 줄 — 검사에 따라 없을 수 있다. */
  tip?: { label: string; text: string };
  /**
   * 카드 게이지를 축 비율 대신 고정 능력치로 그릴 때 쓴다.
   * 수호신 검사처럼 결과별 스탯이 기획서에 못박힌 경우.
   */
  stats?: { name: string; pct: number }[];
  /** 환상의 궁합 / 환장의 궁합 */
  match?: { best: string; worst: string };
  /** 공유 카드에 붙는 한 줄 멘트 */
  mention?: string;
}

export interface TypeTestDef {
  id: string;
  /** 라우트 세그먼트 (/playground/test/:path) */
  path: string;
  /** 선택 카드·탭에 쓰는 짧은 이름 */
  label: string;
  /** 검사 화면 상단의 정식 이름 */
  title: string;
  /** 선택 카드 설명 */
  summary: string;
  /** 시작 화면의 큰 문구 */
  hook: string;
  /** 시작 화면의 보조 문구 */
  sub: string;
  /** 선택 카드의 메타 표기 (예: '6문항 · 4유형') */
  meta: string;
  axes: string[];
  axisColor: Record<string, string>;
  questions: TestQuestion[];
  /** 결과 키 → 결과 카드. 기본은 최고점 축이 곧 결과 키다. */
  results: Record<string, TestResult>;
  /** 축 점수를 결과 키로 바꾼다. 없으면 최고점 축을 그대로 쓴다. */
  resolve?: (scores: Record<string, number>) => string;
  /** 카카오톡 등 공유 문구 템플릿. {name} 자리에 결과 이름이 들어간다. */
  sharePrompt: string;
}

