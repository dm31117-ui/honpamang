/**
 * 기획서의 문항 스코어링은 공격형/방어형 2축인데 결과 카드는 4종이다.
 * 그래서 6문항 중 '공격형'을 고른 횟수(0~6)를 네 구간으로 잘라 카드에 태운다.
 * 공격이 셀수록 정면 돌파(사자), 방어로 기울수록 반전 → 회피 → 은신 순.
 */
function resolveGuardian(scores: Record<string, number>): string {
  const attack = scores['공격형'] ?? 0;
  if (attack >= 5) return '사자';
  if (attack === 4) return '미러볼';
  if (attack >= 2) return '올빼미';
  return '거북이';
}

